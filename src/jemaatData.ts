export function jemaatForMupel(mupel: string): readonly string[] {
  const key = mupel.trim()
  if (JEMAAT_BY_MUPEL[key]) return JEMAAT_BY_MUPEL[key]
  const match = Object.keys(JEMAAT_BY_MUPEL).find((item) => item.startsWith(`${key}(`))
  return match ? JEMAAT_BY_MUPEL[match] : []
}
